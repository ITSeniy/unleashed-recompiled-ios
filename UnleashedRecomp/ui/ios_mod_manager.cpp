static constexpr std::string_view GeneratedHeader = "; Generated by the Unleashed Recompiled iOS launcher";
static constexpr const char* DatabaseName = "ios_mods_db.ini";
static constexpr int MaxScanDepth = 4;
static constexpr int MaxScannedFiles = 1000;
static constexpr uintmax_t MaxSchemaBytes = 1024 * 1024;

static std::filesystem::path FromUtf8(std::string value)
{
    std::replace(value.begin(), value.end(), '\\', '/');
    return std::filesystem::path(std::u8string_view((const char8_t*)value.data(), value.size()));
}

static std::string ToUtf8(const std::filesystem::path& path)
{
    const std::u8string value = path.u8string();
    return std::string((const char*)value.data(), value.size());
}

// Paths in the ini files are relative to the file that names them, as in ModLoader.
static std::filesystem::path Resolve(const std::filesystem::path& owner, const std::string& value)
{
    std::filesystem::path path = FromUtf8(value);
    if (path.is_relative())
        path = owner.parent_path() / path;
    return path.lexically_normal();
}

static std::string Key(const std::filesystem::path& path)
{
    std::error_code ec;
    const auto canonical = std::filesystem::weakly_canonical(path, ec);
    return ToUtf8(ec ? path.lexically_normal() : canonical);
}

static bool IsSupportedModIni(const IniFile& ini)
{
    return ini.contains("Details") || ini.contains("Filesystem") ||
        (ini.contains("Main") && (!ini.getString("Main", "IncludeDirCount", "").empty() ||
            !ini.getString("Main", "IncludeDir0", "").empty()));
}

static std::string FirstValue(const IniFile& ini, std::initializer_list<const char*> sections, std::initializer_list<const char*> keys)
{
    for (const char* section : sections)
    {
        for (const char* key : keys)
        {
            std::string value = ini.getString(section, key, "");
            if (!value.empty())
                return value;
        }
    }
    return {};
}

static bool ReadMod(const std::filesystem::path& iniPath, IOSMod& mod)
{
    IniFile ini;
    if (!ini.read(iniPath) || !IsSupportedModIni(ini))
        return false;

    mod.iniPath = iniPath.lexically_normal();
    mod.title = FirstValue(ini, { "Desc", "Details", "Main" }, { "Title", "Name" });
    if (mod.title.empty())
        mod.title = ToUtf8(iniPath.parent_path().filename());
    mod.author = FirstValue(ini, { "Desc", "Details" }, { "Author" });
    mod.version = FirstValue(ini, { "Desc", "Details" }, { "Version" });

    const std::string schema = ini.getString("Main", "ConfigSchemaFile", "");
    if (!schema.empty())
    {
        const auto root = iniPath.parent_path().lexically_normal();
        const auto schemaPath = Resolve(iniPath, schema);
        const auto relative = schemaPath.lexically_relative(root);
        std::error_code ec;
        const auto size = std::filesystem::file_size(schemaPath, ec);
        if (!relative.empty() && *relative.begin() != ".." && !ec && size > 0 && size <= MaxSchemaBytes)
            mod.schemaPath = schemaPath;
    }
    return true;
}

static bool HasIniExtension(const std::filesystem::path& path)
{
    std::string extension = ToUtf8(path.extension());
    std::transform(extension.begin(), extension.end(), extension.begin(), ::tolower);
    return extension == ".ini";
}

static void Scan(const std::filesystem::path& directory, int depth, int& scannedFiles, std::map<std::string, IOSMod>& result)
{
    std::error_code ec;
    if (depth > MaxScanDepth || scannedFiles >= MaxScannedFiles || !std::filesystem::is_directory(directory, ec))
        return;

    std::vector<std::filesystem::directory_entry> children;
    for (std::filesystem::directory_iterator it(directory, ec), end; !ec && it != end; it.increment(ec))
        children.push_back(*it);
    std::sort(children.begin(), children.end(), [](const auto& a, const auto& b)
    {
        std::string left = ToUtf8(a.path().filename()), right = ToUtf8(b.path().filename());
        std::transform(left.begin(), left.end(), left.begin(), ::tolower);
        std::transform(right.begin(), right.end(), right.begin(), ::tolower);
        return left < right;
    });

    // Read this level's ini files before descending, so a large content folder
    // cannot use up the scan budget before its own mod.ini is seen.
    bool foundMod = false;
    for (const auto& child : children)
    {
        if (child.is_symlink(ec) || !child.is_regular_file(ec) || !HasIniExtension(child.path()))
            continue;

        scannedFiles++;
        IOSMod mod;
        if (ReadMod(child.path(), mod))
        {
            result.emplace(Key(mod.iniPath), std::move(mod));
            foundMod = true;
        }
    }

    // Mods never nest inside another mod's folder.
    if (foundMod)
        return;

    for (const auto& child : children)
    {
        if (scannedFiles >= MaxScannedFiles)
            break;
        if (child.is_symlink(ec))
            continue;
        if (child.is_directory(ec))
            Scan(child.path(), depth + 1, scannedFiles, result);
        else if (!HasIniExtension(child.path()))
            scannedFiles++;
    }
}

static std::filesystem::path FindDatabase()
{
    const auto config = GetUserPath() / "cpkredir.ini";
    IniFile ini;
    if (ini.read(config))
    {
        const std::string database = ini.getString("CPKREDIR", "ModsDbIni", "");
        if (!database.empty())
            return Resolve(config, database);
    }
    return GetUserPath() / DatabaseName;
}

std::filesystem::path ios_mods::GetModsDirectory()
{
    return GetGamePath() / "mods";
}

std::vector<IOSMod> ios_mods::Load()
{
    std::error_code ec;
    std::filesystem::create_directories(GetModsDirectory(), ec);

    std::map<std::string, IOSMod> discovered;
    int scannedFiles = 0;
    Scan(GetModsDirectory(), 0, scannedFiles, discovered);

    std::vector<IOSMod> mods;
    const auto databasePath = FindDatabase();
    IniFile database;
    if (database.read(databasePath))
    {
        const size_t count = database.get<size_t>("Main", "ActiveModCount", 0);
        for (size_t i = 0; i < count; i++)
        {
            const std::string id = database.getString("Main", fmt::format("ActiveMod{}", i), "");
            const std::string path = id.empty() ? std::string() : database.getString("Mods", id, "");
            if (path.empty())
                continue;

            const auto iniPath = Resolve(databasePath, path);
            const auto key = Key(iniPath);
            IOSMod mod;
            if (auto found = discovered.find(key); found != discovered.end())
            {
                mod = std::move(found->second);
                discovered.erase(found);
            }
            else if (!ReadMod(iniPath, mod))
            {
                // Active mods outside the mods folder stay listed; missing ones are dropped.
                continue;
            }
            mod.enabled = true;
            mods.push_back(std::move(mod));
        }
    }

    std::vector<IOSMod> remaining;
    for (auto& [_, mod] : discovered)
        remaining.push_back(std::move(mod));
    std::sort(remaining.begin(), remaining.end(), [](const IOSMod& a, const IOSMod& b)
    {
        std::string left = a.title, right = b.title;
        std::transform(left.begin(), left.end(), left.begin(), ::tolower);
        std::transform(right.begin(), right.end(), right.begin(), ::tolower);
        return left < right;
    });
    mods.insert(mods.end(), std::make_move_iterator(remaining.begin()), std::make_move_iterator(remaining.end()));
    return mods;
}

static bool IsIniSafe(const std::string& value)
{
    return value.find_first_of("\"\r\n") == std::string::npos;
}

static bool WriteAtomic(const std::filesystem::path& target, const std::string& contents, std::string& error)
{
    auto temporary = target;
    temporary += ".tmp";
    {
        std::ofstream file(temporary, std::ios::binary | std::ios::trunc);
        file.write(contents.data(), contents.size());
        if (!file.good())
        {
            error = fmt::format("Cannot write {}.", ToUtf8(temporary.filename()));
            return false;
        }
    }
    std::error_code ec;
    std::filesystem::rename(temporary, target, ec);
    if (ec)
    {
        std::filesystem::remove(temporary, ec);
        error = fmt::format("Cannot replace {}: {}", ToUtf8(target.filename()), ec.message());
        return false;
    }
    return true;
}

static bool IsGeneratedByLauncher(const std::filesystem::path& path)
{
    std::ifstream file(path);
    std::string line;
    return std::getline(file, line) && line.rfind(GeneratedHeader, 0) == 0;
}

bool ios_mods::Save(const std::vector<IOSMod>& mods, std::string& error)
{
    const auto userPath = GetUserPath();
    std::error_code ec;
    std::filesystem::create_directories(userPath, ec);
    const auto databasePath = userPath / DatabaseName;
    const auto configPath = userPath / "cpkredir.ini";

    // Codes stored in a database written by other tools stay active.
    std::vector<std::string> codes;
    IniFile previous;
    if (previous.read(FindDatabase()))
    {
        const size_t count = previous.get<size_t>("Codes", "CodeCount", 0);
        for (size_t i = 0; i < count; i++)
        {
            std::string code = previous.getString("Codes", fmt::format("Code{}", i), "");
            if (!code.empty() && IsIniSafe(code))
                codes.push_back(std::move(code));
        }
    }

    std::string database = fmt::format("{}\n[Main]\n", GeneratedHeader);
    size_t active = 0;
    for (size_t i = 0; i < mods.size(); i++)
    {
        if (mods[i].enabled)
            database += fmt::format("ActiveMod{}=mod{}\n", active++, i);
    }
    database += fmt::format("ActiveModCount={}\n\n[Mods]\n", active);
    for (size_t i = 0; i < mods.size(); i++)
    {
        auto relative = mods[i].iniPath.lexically_relative(userPath);
        const std::string path = ToUtf8(relative.empty() ? mods[i].iniPath : relative);
        if (!IsIniSafe(path))
        {
            error = fmt::format("The path of \"{}\" cannot be stored in the mod database.", mods[i].title);
            return false;
        }
        database += fmt::format("mod{}=\"{}\"\n", i, path);
    }
    database += fmt::format("\n[Codes]\nCodeCount={}\n", codes.size());
    for (size_t i = 0; i < codes.size(); i++)
        database += fmt::format("Code{}={}\n", i, codes[i]);

    if (!WriteAtomic(databasePath, database, error))
        return false;

    // Keep other loader settings (save redirection, log type) from an existing config.
    std::map<std::string, std::string> values;
    IniFile oldConfig;
    if (oldConfig.read(configPath))
    {
        oldConfig.enumerate("CPKREDIR", [&](const std::string& name, const std::string& value)
        {
            if (IsIniSafe(value))
                values[name] = value;
        });

        const auto backup = userPath / "cpkredir.pre_ios_launcher.ini";
        if (!IsGeneratedByLauncher(configPath) && !std::filesystem::exists(backup, ec))
            std::filesystem::copy_file(configPath, backup, ec);
    }
    values["Enabled"] = "true";
    values["ModsDbIni"] = DatabaseName;

    std::string config = fmt::format("{}\n[CPKREDIR]\n", GeneratedHeader);
    for (const auto& [name, value] : values)
        config += fmt::format("{}=\"{}\"\n", name, value);

    if (!WriteAtomic(configPath, config, error))
        return false;

    LOGFN("Saved mod database: {} of {} mods active.", active, mods.size());
    return true;
}

static bool ExtractZip(const std::filesystem::path& archive, const std::filesystem::path& destination, std::string& error)
{
    mz_zip_archive zip{};
    if (!mz_zip_reader_init_file(&zip, ToUtf8(archive).c_str(), 0))
    {
        error = "The file is not a readable ZIP archive.";
        return false;
    }

    bool success = true;
    const mz_uint count = mz_zip_reader_get_num_files(&zip);
    for (mz_uint i = 0; i < count && success; i++)
    {
        mz_zip_archive_file_stat stat;
        if (!mz_zip_reader_file_stat(&zip, i, &stat))
            continue;

        const auto relative = FromUtf8(stat.m_filename).lexically_normal();
        const std::string first = relative.empty() ? std::string() : ToUtf8(*relative.begin());
        if (relative.empty() || first == "__MACOSX" || first == ".")
            continue;
        if (relative.is_absolute() || first == "..")
        {
            error = "The archive contains paths outside its folder.";
            success = false;
            break;
        }

        const auto target = destination / relative;
        std::error_code ec;
        if (stat.m_is_directory)
        {
            std::filesystem::create_directories(target, ec);
            continue;
        }
        std::filesystem::create_directories(target.parent_path(), ec);
        if (!mz_zip_reader_extract_to_file(&zip, i, ToUtf8(target).c_str(), 0))
        {
            error = fmt::format("Cannot extract {}.", stat.m_filename);
            success = false;
        }
    }

    mz_zip_reader_end(&zip);
    return success;
}

int ios_mods::Install(const std::filesystem::path& source, std::string& error)
{
    const auto modsDirectory = GetModsDirectory();
    std::error_code ec;
    std::filesystem::create_directories(modsDirectory, ec);

    std::string extension = ToUtf8(source.extension());
    std::transform(extension.begin(), extension.end(), extension.begin(), ::tolower);
    const bool isZip = extension == ".zip";

    std::string name = ToUtf8(isZip ? source.stem() : source.filename());
    std::erase_if(name, [](char c) { return c == '/' || c == '\\' || c == '"'; });
    while (!name.empty() && name.front() == '.')
        name.erase(name.begin());
    if (name.empty())
        name = "Mod";

    auto destination = modsDirectory / FromUtf8(name);
    for (int i = 2; std::filesystem::exists(destination, ec); i++)
        destination = modsDirectory / FromUtf8(fmt::format("{} ({})", name, i));

    auto temporary = modsDirectory / FromUtf8("." + ToUtf8(destination.filename()) + ".part");
    std::filesystem::remove_all(temporary, ec);
    std::filesystem::create_directories(temporary, ec);

    bool copied;
    if (isZip)
    {
        copied = ExtractZip(source, temporary, error);
    }
    else
    {
        std::filesystem::copy(source, temporary, std::filesystem::copy_options::recursive | std::filesystem::copy_options::skip_symlinks, ec);
        copied = !ec;
        if (ec)
            error = fmt::format("Cannot copy the folder: {}", ec.message());
    }

    std::map<std::string, IOSMod> found;
    int scannedFiles = 0;
    if (copied)
        Scan(temporary, 0, scannedFiles, found);

    if (!copied || found.empty())
    {
        if (copied)
            error = "No mod.ini was found. Choose a mod folder or a ZIP that contains one.";
        std::filesystem::remove_all(temporary, ec);
        return 0;
    }

    std::filesystem::rename(temporary, destination, ec);
    if (ec)
    {
        error = fmt::format("Cannot move the mod into place: {}", ec.message());
        std::filesystem::remove_all(temporary, ec);
        return 0;
    }

    LOGFN("Installed {} mod(s) into {}.", found.size(), ToUtf8(destination.filename()));
    return int(found.size());
}
